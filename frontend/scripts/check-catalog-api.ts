import assert from 'node:assert/strict';
import { apiCategories, apiSubcategories } from '../src/lib/catalogApi';
import { getPaginatedProducts, getProductByIdOrSlug, searchProducts, getFeaturedProducts } from '../src/lib/productQueries';

const requests: URL[] = [];
let fail = false;
globalThis.fetch = async (input) => {
  const url = new URL(String(input), 'https://store.example');
  requests.push(url);
  if (fail) return Response.json({ code: 'CATALOG_UNAVAILABLE' }, { status: 503 });
  if (url.pathname.endsWith('/categories')) return Response.json({ categories: [{ id: 'hair-accessories', name: 'Hair Accessories', image_url: '/media/category.webp' }] });
  if (url.pathname.endsWith('/subcategories')) return Response.json({ subcategories: [{ id: 7, category_id: 'hair-accessories', name: 'Butterfly', slug: 'butterfly', featured_image: '/media/butterfly.webp', is_active: true, sort_order: 1 }] });
  const product = { id: 12, slug: 'clip', title: 'Clip', sale_price: 99, mrp: 120, image_url: '/media/clip.webp', category_id: 'hair-accessories', subcategory_id: 7, in_stock: true };
  return Response.json({ products: [product], count: 25 });
};
const categories = await apiCategories();
const [butterfly] = await apiSubcategories();
assert.equal(categories[0].id, 'hair-accessories');
assert.equal(butterfly.categoryId, categories[0].id);
assert.equal(butterfly.name, 'Butterfly');
assert.equal(butterfly.featuredImage, '/media/butterfly.webp');
const listing = await getPaginatedProducts({ categoryId: categories[0].id, subcategory: butterfly, page: 2, pageSize: 10, sort: 'price-asc' });
assert.equal(listing.count, 25);
assert.equal(listing.products[0].id, 'clip');
const listingUrl = requests.at(-1)!;
assert.equal(listingUrl.pathname, '/api/v1/products');
assert.deepEqual(Object.fromEntries(listingUrl.searchParams), { categoryId: 'hair-accessories', subcategoryId: '7', page: '2', pageSize: '10', sort: 'price-asc' });
await searchProducts('butterfly');
assert.equal(requests.at(-1)!.searchParams.get('q'), 'butterfly');
await getProductByIdOrSlug('clip');
assert.equal(requests.at(-1)!.pathname, '/api/v1/products/resolve');
await getFeaturedProducts();
assert.equal(requests.at(-1)!.searchParams.get('featured'), 'true');
assert.ok(requests.every(url => url.pathname.startsWith('/api/v1/')));
fail = true;
await assert.rejects(apiSubcategories(), /CATALOG_UNAVAILABLE/);
await assert.rejects(getPaginatedProducts(), /CATALOG_UNAVAILABLE/);
console.log('Catalog API request, filtering, media mapping and error checks passed.');
